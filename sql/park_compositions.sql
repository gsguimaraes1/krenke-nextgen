-- ── 1. Composição padrão de cada parque ──────────────────────────────
create table if not exists public.park_compositions (
  id uuid primary key default gen_random_uuid(),
  park_id text not null references public.products(id) on delete cascade,
  product_code text not null,
  -- descrição exata em calculator_products (código 200565 é compartilhado por 4 telhados)
  product_description text not null,
  qty integer not null check (qty > 0),
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  unique (park_id, product_code, product_description)
);
create index if not exists park_compositions_park_id_idx on public.park_compositions (park_id);

alter table public.park_compositions enable row level security;

drop policy if exists park_compositions_select on public.park_compositions;
create policy park_compositions_select on public.park_compositions
  for select to authenticated using (true);

drop policy if exists park_compositions_write on public.park_compositions;
create policy park_compositions_write on public.park_compositions
  for all to authenticated
  using (public.is_super_admin()) with check (public.is_super_admin());

-- ── 2. Flags de revisão (só super admin lê/escreve) ─────────────────
create table if not exists public.calculator_product_reviews (
  id uuid primary key default gen_random_uuid(),
  product_code text not null,
  product_description text not null,
  reference_price numeric(12,2),
  reference_description text,
  note text,
  resolved boolean not null default false,
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  unique (product_code, product_description)
);

alter table public.calculator_product_reviews enable row level security;

drop policy if exists calculator_product_reviews_super on public.calculator_product_reviews;
create policy calculator_product_reviews_super on public.calculator_product_reviews
  for all to authenticated
  using (public.is_super_admin()) with check (public.is_super_admin());

